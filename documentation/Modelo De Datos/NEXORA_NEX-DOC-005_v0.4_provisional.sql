-- Valida membresias y serializa cambios de miembros/invitaciones por lista.
CREATE OR REPLACE FUNCTION validate_list_membership_write()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_owner_id integer;
    v_list_type varchar(20);
BEGIN
    IF TG_OP = 'DELETE' THEN
        -- Bloquea la lista mientras se modifica su conjunto de miembros.
        PERFORM 1 FROM task_lists WHERE id = OLD.list_id FOR UPDATE;
        RETURN OLD;
    END IF;

    SELECT owner_id, list_type
      INTO v_owner_id, v_list_type
      FROM task_lists
     WHERE id = NEW.list_id
     FOR UPDATE;

    IF FOUND AND v_list_type = 'personal' AND NEW.user_id <> v_owner_id THEN
        RAISE EXCEPTION 'Una lista personal solo puede tener como miembro a su propietario';
    END IF;

    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_list_memberships_validate
BEFORE INSERT OR UPDATE OR DELETE ON list_memberships
FOR EACH ROW EXECUTE FUNCTION validate_list_membership_write();

-- Comprueba al COMMIT que toda lista conserva la membresia del propietario.
-- Si la lista es personal, tambien comprueba que no tenga otros miembros.
CREATE OR REPLACE FUNCTION assert_list_owner_membership()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_list_ids integer[];
    v_list_id integer;
    v_owner_id integer;
    v_list_type varchar(20);
BEGIN
    IF TG_TABLE_NAME = 'task_lists' THEN
        v_list_ids := ARRAY[NEW.id];
    ELSIF TG_OP = 'INSERT' THEN
        v_list_ids := ARRAY[NEW.list_id];
    ELSIF TG_OP = 'DELETE' THEN
        v_list_ids := ARRAY[OLD.list_id];
    ELSE
        v_list_ids := ARRAY[OLD.list_id, NEW.list_id];
    END IF;

    FOREACH v_list_id IN ARRAY v_list_ids LOOP
        IF v_list_id IS NULL THEN
            CONTINUE;
        END IF;

        SELECT owner_id, list_type
          INTO v_owner_id, v_list_type
          FROM task_lists
         WHERE id = v_list_id;

        -- La lista puede haber sido eliminada; en ese caso no hay nada que validar.
        IF NOT FOUND THEN
            CONTINUE;
        END IF;

        IF NOT EXISTS (
            SELECT 1 FROM list_memberships
             WHERE list_id = v_list_id AND user_id = v_owner_id
        ) THEN
            RAISE EXCEPTION 'El propietario % debe pertenecer a la lista %', v_owner_id, v_list_id;
        END IF;

        IF v_list_type = 'personal' AND EXISTS (
            SELECT 1 FROM list_memberships
             WHERE list_id = v_list_id AND user_id <> v_owner_id
        ) THEN
            RAISE EXCEPTION 'Una lista personal no puede tener miembros distintos de su propietario';
        END IF;
    END LOOP;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER ct_task_lists_owner_membership
AFTER INSERT OR UPDATE ON task_lists
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION assert_list_owner_membership();
CREATE CONSTRAINT TRIGGER ct_list_memberships_owner_membership
AFTER INSERT OR UPDATE OR DELETE ON list_memberships
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION assert_list_owner_membership();

-- Una lista compartida puede convertirse en personal solo si no quedan
-- invitados, responsables ni miembros ajenos al propietario.
CREATE OR REPLACE FUNCTION validate_list_type_change()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.list_type = 'personal' AND OLD.list_type IS DISTINCT FROM NEW.list_type THEN
        IF EXISTS (
            SELECT 1 FROM list_memberships
             WHERE list_id = OLD.id AND user_id <> NEW.owner_id
        ) THEN
            RAISE EXCEPTION 'No se puede convertir en personal una lista con otros miembros';
        END IF;
        IF EXISTS (SELECT 1 FROM invitations WHERE list_id = OLD.id) THEN
            RAISE EXCEPTION 'Elimina las invitaciones antes de convertir la lista en personal';
        END IF;
        IF EXISTS (SELECT 1 FROM task_assignees WHERE list_id = OLD.id) THEN
            RAISE EXCEPTION 'Elimina las asignaciones antes de convertir la lista en personal';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_task_lists_type_change
BEFORE UPDATE OF list_type ON task_lists
FOR EACH ROW EXECUTE FUNCTION validate_list_type_change();

-- Las tareas solo pueden asignarse en listas compartidas.
-- La FK compuesta ya garantiza que cada responsable sea miembro de esa lista.
CREATE OR REPLACE FUNCTION validate_task_assignee_list_type()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_list_type varchar(20);
BEGIN
    -- Bloquea la fila de la lista hasta terminar la transaccion.
    -- Asi se serializa la asignacion frente a un cambio shared -> personal.
    SELECT list_type
      INTO v_list_type
      FROM task_lists
     WHERE id = NEW.list_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RETURN NEW; -- La FK compuesta informara despues si la lista no existe.
    END IF;

    IF v_list_type <> 'shared' THEN
        RAISE EXCEPTION 'Solo se pueden asignar tareas de listas compartidas';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_task_assignees_shared_only
BEFORE INSERT OR UPDATE ON task_assignees
FOR EACH ROW EXECUTE FUNCTION validate_task_assignee_list_type();

-- Invitaciones: solo a listas compartidas, no al propietario ni a miembros actuales.
-- La FK compuesta garantiza que inviter_user_id sea el propietario.
CREATE OR REPLACE FUNCTION validate_invitation_write()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_owner_id integer;
    v_list_type varchar(20);
    v_target_changed boolean := true;
BEGIN
    -- Toda invitacion nace pendiente. Los estados finales solo se alcanzan
    -- mediante una transicion UPDATE validada por el trigger correspondiente.
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'pending' OR NEW.responded_at IS NOT NULL THEN
            RAISE EXCEPTION 'Una invitacion nueva debe comenzar en estado pending';
        END IF;
    END IF;

    SELECT owner_id, list_type
      INTO v_owner_id, v_list_type
      FROM task_lists
     WHERE id = NEW.list_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RETURN NEW; -- La FK informara del identificador inexistente.
    END IF;

    IF v_list_type <> 'shared' THEN
        RAISE EXCEPTION 'No se pueden enviar invitaciones a listas personales';
    END IF;

    IF NEW.invited_user_id = v_owner_id THEN
        RAISE EXCEPTION 'No se puede invitar al propietario de la lista';
    END IF;

    IF TG_OP = 'UPDATE' THEN
        v_target_changed := (NEW.list_id IS DISTINCT FROM OLD.list_id)
                         OR (NEW.invited_user_id IS DISTINCT FROM OLD.invited_user_id);
    END IF;

    IF v_target_changed AND EXISTS (
        SELECT 1 FROM list_memberships
         WHERE list_id = NEW.list_id AND user_id = NEW.invited_user_id
    ) THEN
        RAISE EXCEPTION 'El usuario ya pertenece a esta lista';
    END IF;

    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_invitations_validate
BEFORE INSERT OR UPDATE ON invitations
FOR EACH ROW EXECUTE FUNCTION validate_invitation_write();

-- Las invitaciones solo pueden pasar de pending a un estado final.
CREATE OR REPLACE FUNCTION validate_invitation_transition()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.status IS DISTINCT FROM OLD.status THEN
        IF OLD.status <> 'pending' THEN
            RAISE EXCEPTION 'Una invitacion respondida no puede cambiar de estado';
        END IF;
        IF NEW.status NOT IN ('accepted', 'rejected', 'cancelled') THEN
            RAISE EXCEPTION 'Transicion de invitacion no permitida';
        END IF;
        NEW.responded_at := COALESCE(NEW.responded_at, now());
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_invitations_transition
BEFORE UPDATE OF status ON invitations
FOR EACH ROW EXECUTE FUNCTION validate_invitation_transition();

-- Aceptar la invitacion crea la membresia dentro de la misma transaccion.
CREATE OR REPLACE FUNCTION add_membership_after_invitation_acceptance()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO list_memberships(user_id, list_id)
    VALUES (NEW.invited_user_id, NEW.list_id)
    ON CONFLICT (user_id, list_id) DO NOTHING;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_invitation_accepted_membership
AFTER UPDATE OF status ON invitations
FOR EACH ROW
WHEN (OLD.status = 'pending' AND NEW.status = 'accepted')
EXECUTE FUNCTION add_membership_after_invitation_acceptance();

-- completed_at se actualiza al cambiar el estado.
CREATE OR REPLACE FUNCTION maintain_task_completed_at()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.status = 'done' THEN
            NEW.completed_at := now();
        ELSE
            NEW.completed_at := NULL;
        END IF;
    ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
        IF NEW.status = 'done' THEN
            NEW.completed_at := now();
        ELSE
            NEW.completed_at := NULL;
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_tasks_completed_at
BEFORE INSERT OR UPDATE OF status ON tasks
FOR EACH ROW EXECUTE FUNCTION maintain_task_completed_at();

-- El historial se escribe automaticamente. Para cambios posteriores a la
-- creacion, la API debe ejecutar SET LOCAL app.user_id = '<id>' en la transaccion.
CREATE OR REPLACE FUNCTION log_task_status_change()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_actor_id integer;
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO task_status_changes(task_id, old_status, new_status, changed_by)
        VALUES (NEW.id, NULL, NEW.status, NEW.creator_id);
        RETURN NEW;
    END IF;

    IF NEW.status IS DISTINCT FROM OLD.status THEN
        IF NULLIF(current_setting('app.user_id', true), '') IS NULL THEN
            RAISE EXCEPTION 'Debes establecer SET LOCAL app.user_id antes de cambiar el estado de una tarea';
        END IF;
        v_actor_id := current_setting('app.user_id', true)::integer;
        INSERT INTO task_status_changes(task_id, old_status, new_status, changed_by)
        VALUES (NEW.id, OLD.status, NEW.status, v_actor_id);
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_tasks_status_history_insert
AFTER INSERT ON tasks
FOR EACH ROW EXECUTE FUNCTION log_task_status_change();
CREATE TRIGGER trg_tasks_status_history_update
AFTER UPDATE OF status ON tasks
FOR EACH ROW EXECUTE FUNCTION log_task_status_change();

-- Al crear una nueva solicitud, se invalidan las anteriores no usadas.
-- El bloqueo de la fila del usuario evita solicitudes activas concurrentes
-- para la misma cuenta; el indice UNIQUE parcial es una segunda barrera.
CREATE OR REPLACE FUNCTION invalidate_previous_password_resets()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    PERFORM 1 FROM users WHERE id = NEW.user_id FOR UPDATE;
    UPDATE password_resets
       SET invalidated_at = now()
     WHERE user_id = NEW.user_id
       AND used_at IS NULL
       AND invalidated_at IS NULL;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_password_resets_invalidate_previous
BEFORE INSERT ON password_resets
FOR EACH ROW EXECUTE FUNCTION invalidate_previous_password_resets();

COMMIT;

