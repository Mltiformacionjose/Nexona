-- 1. USERS
CREATE TABLE users (
    id                    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username              varchar(50)  NOT NULL,
    email                 varchar(255) NOT NULL,
    password_hash         varchar(255) NOT NULL,
    notifications_enabled boolean      NOT NULL DEFAULT true,
    created_at            timestamptz  NOT NULL DEFAULT now(),
    updated_at            timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_users_username_lower ON users (lower(username));
CREATE UNIQUE INDEX uq_users_email_lower ON users (lower(email));

-- 2. TASK_LISTS
CREATE TABLE task_lists (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(150) NOT NULL,
    description varchar(500),
    list_type  varchar(20) NOT NULL,
    owner_id   integer NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_task_lists_owner
        FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT ck_task_lists_type
        CHECK (list_type IN ('personal', 'shared')),
    -- Necesaria para la FK compuesta de invitations.
    CONSTRAINT uq_task_lists_id_owner UNIQUE (id, owner_id)
);
CREATE INDEX ix_task_lists_owner_id ON task_lists(owner_id);
CREATE INDEX ix_task_lists_type ON task_lists(list_type);

-- 3. LIST_MEMBERSHIPS
CREATE TABLE list_memberships (
    user_id  integer NOT NULL,
    list_id  integer NOT NULL,
    joined_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_list_memberships PRIMARY KEY (user_id, list_id),
    CONSTRAINT fk_list_memberships_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_list_memberships_list
        FOREIGN KEY (list_id) REFERENCES task_lists(id) ON DELETE CASCADE
);
CREATE INDEX ix_list_memberships_list_id ON list_memberships(list_id);

-- 4. TASKS
CREATE TABLE tasks (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    list_id      integer NOT NULL,
    title        varchar(150) NOT NULL,
    description  text,
    due_date     date,
    status       varchar(20) NOT NULL DEFAULT 'todo',
    creator_id   integer NOT NULL,
    completed_at timestamptz,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_tasks_list
        FOREIGN KEY (list_id) REFERENCES task_lists(id) ON DELETE CASCADE,
    CONSTRAINT fk_tasks_creator
        FOREIGN KEY (creator_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT ck_tasks_status
        CHECK (status IN ('todo', 'in_progress', 'done')),
    CONSTRAINT ck_tasks_completed_at
        CHECK (
            (status = 'done' AND completed_at IS NOT NULL)
            OR (status <> 'done' AND completed_at IS NULL)
        ),
    -- Necesaria para comprobar que una asignacion pertenece a la lista correcta.
    CONSTRAINT uq_tasks_id_list UNIQUE (id, list_id)
);
CREATE INDEX ix_tasks_list_id ON tasks(list_id);
CREATE INDEX ix_tasks_list_status ON tasks(list_id, status);
CREATE INDEX ix_tasks_due_date ON tasks(due_date);
CREATE INDEX ix_tasks_creator_id ON tasks(creator_id);

-- 5. TASK_ASSIGNEES
-- list_id se repite intencionadamente para poder expresar dos FK compuestas:
-- (task_id, list_id) -> tasks y (user_id, list_id) -> list_memberships.
CREATE TABLE task_assignees (
    task_id     integer NOT NULL,
    list_id     integer NOT NULL,
    user_id     integer NOT NULL,
    assigned_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_task_assignees PRIMARY KEY (task_id, user_id),
    CONSTRAINT fk_task_assignees_task_list
        FOREIGN KEY (task_id, list_id)
        REFERENCES tasks(id, list_id) ON DELETE CASCADE,
    CONSTRAINT fk_task_assignees_membership
        FOREIGN KEY (user_id, list_id)
        REFERENCES list_memberships(user_id, list_id) ON DELETE CASCADE
);
CREATE INDEX ix_task_assignees_user_id ON task_assignees(user_id);
CREATE INDEX ix_task_assignees_list_id ON task_assignees(list_id);

-- 6. TASK_STATUS_CHANGES
CREATE TABLE task_status_changes (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id    integer NOT NULL,
    old_status varchar(20),
    new_status varchar(20) NOT NULL,
    changed_by integer NOT NULL,
    changed_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_task_status_changes_task
        FOREIGN KEY (task_id) REFERENCES tasks(id) ON DELETE CASCADE,
    CONSTRAINT fk_task_status_changes_user
        FOREIGN KEY (changed_by) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT ck_task_status_changes_old
        CHECK (old_status IS NULL OR old_status IN ('todo', 'in_progress', 'done')),
    CONSTRAINT ck_task_status_changes_new
        CHECK (new_status IN ('todo', 'in_progress', 'done'))
);
CREATE INDEX ix_task_status_changes_task_date ON task_status_changes(task_id, changed_at);
CREATE INDEX ix_task_status_changes_user ON task_status_changes(changed_by);

-- El historial no se edita ni se elimina manualmente.
-- Se permite el DELETE anidado que PostgreSQL ejecuta por ON DELETE CASCADE
-- cuando se elimina la tarea propietaria. pg_trigger_depth() distingue ese
-- borrado referencial de un DELETE directo sobre esta tabla.
CREATE OR REPLACE FUNCTION protect_task_status_changes()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        -- Solo los triggers de tasks pueden generar filas de historial.
        IF pg_trigger_depth() <= 1 THEN
            RAISE EXCEPTION 'El historial solo puede generarse mediante cambios reales en tasks';
        END IF;
        RETURN NEW;
    END IF;

    IF TG_OP = 'UPDATE' THEN
        RAISE EXCEPTION 'El historial de estados es inmutable y no admite UPDATE';
    END IF;

    IF TG_OP = 'DELETE' AND pg_trigger_depth() <= 1 THEN
        RAISE EXCEPTION 'El historial solo se elimina mediante el borrado en cascada de su tarea';
    END IF;

    RETURN OLD;
END;
$$;
CREATE TRIGGER trg_task_status_changes_immutable
BEFORE INSERT OR UPDATE OR DELETE ON task_status_changes
FOR EACH ROW EXECUTE FUNCTION protect_task_status_changes();

CREATE OR REPLACE FUNCTION prevent_task_status_changes_truncate()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'No se permite TRUNCATE sobre el historial de estados';
    RETURN NULL; -- Inalcanzable; explicita el tipo de retorno del trigger.
END;
$$;
CREATE TRIGGER trg_task_status_changes_no_truncate
BEFORE TRUNCATE ON task_status_changes
FOR EACH STATEMENT EXECUTE FUNCTION prevent_task_status_changes_truncate();

-- 7. INVITATIONS
CREATE TABLE invitations (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    list_id        integer NOT NULL,
    invited_user_id integer NOT NULL,
    inviter_user_id integer NOT NULL,
    status         varchar(20) NOT NULL DEFAULT 'pending',
    created_at     timestamptz NOT NULL DEFAULT now(),
    responded_at   timestamptz,
    CONSTRAINT fk_invitations_list
        FOREIGN KEY (list_id) REFERENCES task_lists(id) ON DELETE CASCADE,
    CONSTRAINT fk_invitations_invited_user
        FOREIGN KEY (invited_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    -- Garantiza en la propia base de datos que el invitador sea el propietario.
    CONSTRAINT fk_invitations_owner
        FOREIGN KEY (list_id, inviter_user_id)
        REFERENCES task_lists(id, owner_id) ON DELETE CASCADE,
    CONSTRAINT ck_invitations_status
        CHECK (status IN ('pending', 'accepted', 'rejected', 'cancelled')),
    CONSTRAINT ck_invitations_responded_at
        CHECK (
            (status = 'pending' AND responded_at IS NULL)
            OR (status <> 'pending' AND responded_at IS NOT NULL)
        ),
    CONSTRAINT uq_invitations_id_list UNIQUE (id, list_id)
);
CREATE INDEX ix_invitations_list_id ON invitations(list_id);
CREATE INDEX ix_invitations_list_status ON invitations(list_id, status);
CREATE INDEX ix_invitations_user_status ON invitations(invited_user_id, status);
CREATE INDEX ix_invitations_inviter ON invitations(inviter_user_id);
CREATE UNIQUE INDEX uq_invitations_pending_list_user
    ON invitations(list_id, invited_user_id)
    WHERE status = 'pending';

-- 8. NOTIFICATIONS
-- list_id es obligatorio para que las FK compuestas validen que la
-- tarea/invitacion relacionada pertenece realmente a esa lista.
CREATE TABLE notifications (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id integer NOT NULL,
    notification_type varchar(30) NOT NULL,
    task_id           integer,
    list_id           integer NOT NULL,
    invitation_id     integer,
    created_at        timestamptz NOT NULL DEFAULT now(),
    read_at           timestamptz,
    CONSTRAINT fk_notifications_recipient
        FOREIGN KEY (recipient_user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_notifications_list
        FOREIGN KEY (list_id) REFERENCES task_lists(id) ON DELETE CASCADE,
    CONSTRAINT fk_notifications_task_list
        FOREIGN KEY (task_id, list_id)
        REFERENCES tasks(id, list_id) ON DELETE CASCADE,
    CONSTRAINT fk_notifications_invitation_list
        FOREIGN KEY (invitation_id, list_id)
        REFERENCES invitations(id, list_id) ON DELETE CASCADE,
    CONSTRAINT ck_notifications_type
        CHECK (notification_type IN ('task_assigned', 'task_overdue', 'invitation_received')),
    CONSTRAINT ck_notifications_related_entity
        CHECK (
            (notification_type IN ('task_assigned', 'task_overdue')
                AND task_id IS NOT NULL AND invitation_id IS NULL)
            OR
            (notification_type = 'invitation_received'
                AND invitation_id IS NOT NULL AND task_id IS NULL)
        )
);
CREATE INDEX ix_notifications_recipient ON notifications(recipient_user_id);
CREATE INDEX ix_notifications_user_read_date
    ON notifications(recipient_user_id, read_at, created_at);
CREATE INDEX ix_notifications_task ON notifications(task_id);
CREATE INDEX ix_notifications_list ON notifications(list_id);
CREATE INDEX ix_notifications_invitation ON notifications(invitation_id);
CREATE UNIQUE INDEX uq_notifications_overdue_user_task
    ON notifications(recipient_user_id, task_id)
    WHERE notification_type = 'task_overdue';

